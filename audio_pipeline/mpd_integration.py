def select_next_recommendations(
    collection,
    current_track_id: str,
    id_to_file_map: dict,
    k: int = CANDIDATES_K,
    history: deque | list = None,
    queued_files: set = None,
    failed_tracks: set = None,
    selection_mode: str = SELECTION_MODE,
    top_n: int = TOP_N_VARIETY,
    random_seed: int | None = RANDOM_SEED,
    msg_queue: queue.Queue = None,
    recommendation_mode: str = "similarity",
    use_feedback: bool = True,
    seed_songid: str = "",
    gatilho: str = "player",
    record_audit: bool = True
) -> tuple[str, dict, int] | None:
    """
    Seleciona a melhor candidata evitando histórico, fila atual e faixas com falha.
    Suporta recommendation_mode='similarity' (K-NN padrão) ou recommendation_mode='cluster'
    (prioriza faixas pertencentes ao mesmo cluster sonoro da faixa atual).
    Quando use_feedback=True, aplica adaptação Rocchio na consulta e re-ranking com penalidades por skip.
    """
    if history is None:
        history = []
    if queued_files is None:
        queued_files = set()
    if failed_tracks is None:
        failed_tracks = set()

    result = collection.get(ids=[current_track_id], include=["embeddings", "metadatas"])
    embeddings_list = result.get('embeddings')
    if embeddings_list is None or len(embeddings_list) == 0:
        return None

    import numpy as np
    query_emb = np.array(result['embeddings'][0])
    current_meta = result.get('metadatas', [{}])[0] if result.get('metadatas') else {}
    current_cluster = current_meta.get('cluster_id') if current_meta else None
    current_cluster_nome = current_meta.get('cluster_nome') if current_meta else None

    # Aplicação de Rocchio na consulta vetorial se feedback estiver ativo
    search_emb = query_emb
    feedback_engine = None
    if use_feedback and HAS_FEEDBACK:
        try:
            feedback_engine = feedback.FeedbackEngine()
            search_emb, roc_stats = feedback_engine.compute_rocchio_query(query_emb, collection)
            if roc_stats.get("applied") and msg_queue:
                msg_queue.put({"type": "log", "text": f"Rocchio ativo ({roc_stats['n_pos']} pos, {roc_stats['n_neg']} skips)"})
        except Exception as e:
            logging.warning(f"Erro ao calcular Rocchio: {e}")
            search_emb = query_emb

    similares = []
    search_k = feedback_config.CANDIDATES_N if (use_feedback and HAS_FEEDBACK) else k

    # Se modo for cluster e houver cluster válido associado
    if recommendation_mode == "cluster" and current_cluster and current_cluster != "ruido":
        try:
            cluster_tracks = collection.get(
                where={"cluster_id": current_cluster},
                include=["embeddings", "metadatas"]
            )
            c_ids = cluster_tracks.get("ids", [])
            c_embs = cluster_tracks.get("embeddings", [])
            c_metas = cluster_tracks.get("metadatas", [])

            cluster_candidates = []
            norm_q = search_emb / (np.linalg.norm(search_emb) + 1e-9)

            for cid, cemb, cmeta in zip(c_ids, c_embs, c_metas):
                if cid == current_track_id:
                    continue
                emb_arr = np.array(cemb)
                norm_c = emb_arr / (np.linalg.norm(emb_arr) + 1e-9)
                cos_sim = float(np.dot(norm_q, norm_c))
                dist = 1.0 - cos_sim
                cluster_candidates.append({
                    "track_id": cid,
                    "filename": cmeta.get("filename", "") if cmeta else "",
                    "distance": dist,
                    "subgenero": cmeta.get("subgenero", "") if cmeta else "",
                    "cluster_id": current_cluster
                })

            # Ordena por menor distância (maior similaridade dentro do cluster)
            cluster_candidates.sort(key=lambda x: x["distance"])
            similares = cluster_candidates[:search_k]
            if similares and msg_queue:
                display_name = current_cluster_nome or current_cluster
                msg_queue.put({"type": "log", "text": f"Modo Cluster ativo: {display_name} ({current_cluster}) ({len(similares)} candidatas)"})
        except Exception as e:
            logging.warning(f"Erro ao consultar faixas do mesmo cluster '{current_cluster}': {e}. Usando fallback K-NN.")

    # Se não for modo cluster ou não retornou candidatas, usa K-NN padrão
    if not similares:
        similares = vector_store.query_similar(collection, search_emb, k=search_k, exclude_id=current_track_id)

    if not similares:
        return None

    # Re-ranking com penalidades de feedback se ativo
    if use_feedback and HAS_FEEDBACK and feedback_engine:
        try:
            reranked = feedback_engine.rerank_candidates(
                query_emb=query_emb,
                candidates=similares,
                collection=collection,
                id_to_file_map=id_to_file_map,
                queued_files=queued_files
            )
            if reranked:
                similares = reranked[:k]
                if msg_queue:
                    top_cand = similares[0]
                    pen_str = f"pen_g={top_cand.get('genre_penalty', 0):.2f}"
                    msg_queue.put({"type": "log", "text": f"Re-ranking feedback aplicado ({len(similares)} candidatas, {pen_str})"})
        except Exception as e:
            logging.warning(f"Erro ao aplicar re-ranking de feedback: {e}")

    hist_set = set(history)

    def filter_candidates(effective_hist_set: set) -> list[tuple[int, dict]]:
        valid = []
        for rank, rec in enumerate(similares):
            rec_id = rec['track_id']
            rec_file = id_to_file_map.get(rec_id)

            if rec_id in failed_tracks:
                continue

            if rec_id in effective_hist_set:
                logging.debug(f"Candidata '{rec_id}' rejeitada (motivo: no histórico)")
                continue

            if rec_file and (rec_file in queued_files or normalize_mpd_filepath(rec_file) in queued_files):
                logging.info(f"Candidata '{rec_file}' rejeitada (motivo: na fila)")
                if msg_queue:
                    msg_queue.put({"type": "log", "text": f"Rejeitada {os.path.basename(rec_file)} (já na fila)"})
                continue

            if rec_file:
                valid.append((rank, rec))
        return valid

    valid_candidates = filter_candidates(hist_set)

    # Esgotamento: se todas forem rejeitadas por estarem no histórico, descartar entradas mais antigas
    if not valid_candidates and hist_set:
        logging.warning("Todas as candidatas estão no histórico. Descartando entradas mais antigas do histórico...")
        if msg_queue:
            msg_queue.put({"type": "log", "text": "Histórico esgotado: relaxando histórico antigo"})
        temp_hist = list(history)
        while temp_hist and not valid_candidates:
            temp_hist.pop(0)  # remove mais antiga
            valid_candidates = filter_candidates(set(temp_hist))

    if not valid_candidates:
        return None

    # Variedade configurável
    rng = random.Random(random_seed) if random_seed is not None else random

    if selection_mode == "first" or len(valid_candidates) == 1:
        chosen_rank, chosen_rec = valid_candidates[0]
    elif selection_mode == "mmr":
        cand_list = [c for _, c in valid_candidates[:top_n]]
        chosen_rec = compute_mmr_selection(cand_list, collection, history if isinstance(history, deque) else deque(history))
        chosen_rank = next(r for r, c in valid_candidates if c['track_id'] == chosen_rec['track_id'])
    else:  # "random_top_n" (padrão)
        pool = valid_candidates[:top_n]
        chosen_rank, chosen_rec = rng.choice(pool)

    chosen_file = id_to_file_map.get(chosen_rec['track_id'])

    # ── Auditoria e Log Detalhado da Decisão ──────────────────────────────
    is_exploration = (chosen_rank > 0)
    origem = "exploracao" if is_exploration else "recomendada"

    seed_file = id_to_file_map.get(current_track_id, "")
    seed_name = os.path.basename(seed_file) if seed_file else current_track_id
    seed_genero = current_meta.get("subgenero", "Desconhecido")

    genre_penalties = {}
    events_str = "Nenhum"
    q_norm_val = float(np.linalg.norm(search_emb))
    q_summary = f"||q'||={q_norm_val:.3f}"

    if feedback_engine:
        genre_penalties = feedback_engine.storage.get_genre_penalties()
        if roc_stats.get("applied"):
            q_summary += f" (Rocchio: {roc_stats['n_pos']} pos, {roc_stats['n_neg']} neg)"

        recent_pos = roc_stats.get("pos_events", [])
        recent_neg = roc_stats.get("neg_events", [])
        all_evs = sorted(recent_pos + recent_neg, key=lambda x: str(x.get("timestamp", "")), reverse=True)
        if all_evs:
            events_str = ", ".join([
                f"[{str(e.get('timestamp', ''))[:19]}] {e.get('tipo', '').upper()}:{e.get('genero', '')} ({e.get('elapsed', 0):.0f}s)"
                for e in all_evs[:4]
            ])
            if len(all_evs) > 4:
                events_str += f" (+{len(all_evs)-4} outros)"

    pen_str = ", ".join([f"{g}: {val:.2f}" for g, val in genre_penalties.items() if val > 0]) or "Nenhuma"
    cand_name = os.path.basename(chosen_file) if chosen_file else chosen_rec['track_id']
    cand_gen = chosen_rec.get("subgenero", "Desconhecido")
    final_score = chosen_rec.get("final_score", float(1.0 - chosen_rec.get("distance", 1.0)))

    logging.info(
        f"\n[AUDITORIA DE RECOMENDAÇÃO]\n"
        f"  • Seed Usado:          {seed_name} (Gênero: {seed_genero}, ID: {current_track_id})\n"
        f"  • Consulta q':         {q_summary}\n"
        f"  • Penalidades Gênero:  {pen_str}\n"
        f"  • Eventos Feedback:    {events_str}\n"
        f"  • Faixa Escolhida:     {cand_name} (Gênero: {cand_gen})\n"
        f"  • Cota de Exploração:  {'SIM (escolha rank #' + str(chosen_rank + 1) + ')' if is_exploration else 'NÃO (melhor score rank #1)'}\n"
        f"  • Score Final:         {final_score:.4f}"
    )

    # Gravar decisão no SQLite feedback.db (modo WAL) para leitura concorrente pelo monitor
    if feedback_engine and record_audit:
        try:
            candidatas_detalhes = []
            for rank_idx, cand in enumerate(similares[:15]):
                c_id = cand.get("track_id", "")
                c_f = id_to_file_map.get(c_id, "")
                candidatas_detalhes.append({
                    "rank": rank_idx + 1,
                    "track_id": c_id,
                    "filename": os.path.basename(c_f) if c_f else c_id,
                    "subgenero": cand.get("subgenero", ""),
                    "cluster_nome": cand.get("cluster_nome", str(cand.get("cluster_id", ""))),
                    "sim_query": cand.get("sim_query", float(1.0 - cand.get("distance", 1.0))),
                    "track_penalty": cand.get("track_penalty", 0.0),
                    "genre_penalty": cand.get("genre_penalty", 0.0),
                    "final_score": cand.get("final_score", float(1.0 - cand.get("distance", 1.0))),
                    "motivo": "Selecionada" if c_id == chosen_rec['track_id'] else cand.get("motivo", "Candidata alternativa"),
                    "rejeitada": cand.get("rejeitada", False)
                })

            dec_id = feedback_engine.storage.record_decision(
                seed_track_id=current_track_id,
                seed_caminho=seed_file,
                seed_genero=seed_genero,
                escolhida_track_id=chosen_rec['track_id'],
                escolhida_caminho=chosen_file or "",
                escolhida_genero=cand_gen,
                escolhida_cluster=str(chosen_rec.get("cluster_id", "")),
                origem=origem,
                rank_escolhido=chosen_rank,
                score_escolhido=final_score,
                penalidades=genre_penalties,
                candidatas_detalhes=candidatas_detalhes,
                seed_songid=seed_songid,
                gatilho=gatilho
            )
            chosen_rec['decision_id'] = dec_id
        except Exception as e:
            logging.warning(f"Erro ao registrar auditoria no feedback.db: {e}")

    return chosen_file, chosen_rec, chosen_rank

def replenish_mpd_queue(
    client: MPDClient,
    collection,
    current_track_id: str,
    file_to_id_map: dict,
    id_to_file_map: dict,
    music_root: str,
    play_history: deque,
    failed_tracks: set,
    min_queue_ahead: int = MIN_QUEUE_AHEAD,
    max_tries: int = MAX_REPLENISH_TRIES,
    selection_mode: str = SELECTION_MODE,
    top_n: int = TOP_N_VARIETY,
    random_seed: int | None = RANDOM_SEED,
    msg_queue: queue.Queue = None,
    on_rec_success: callable = None,
    on_error: callable = None,
    recommendation_mode: str = "similarity",
    use_feedback: bool = True,
    seed_songid: str = "",
    gatilho: str = "player"
) -> int:
    """Garante que a fila do MPD tenha pelo menos `min_queue_ahead` faixas à frente da atual."""
    feedback_storage = None
    if use_feedback and HAS_FEEDBACK:
        try:
            feedback_storage = feedback.FeedbackStorage()
        except Exception:
            pass

    status = client.status()
    current_pos = int(status.get("song", -1))

    # Requisito 4: Substituir em vez de acrescentar
    # Antes de enfileirar uma decisão, remover (deleteid) faixas não tocadas que o recomendador adicionou
    mpd_purge_pending_recommendations(
        client=client,
        current_pos=current_pos,
        reason=f"Substituição por nova decisão (seed={current_track_id}, songid={seed_songid})",
        feedback_storage=feedback_storage
    )

    playlist = client.playlistinfo()
    status = client.status()
    current_pos = int(status.get("song", -1))

    if current_pos == -1:
        ahead = len(playlist)
    else:
        ahead = len(playlist) - (current_pos + 1)

    added_count = 0
    attempts = 0
    current_decision_id = None

    # A busca de reposição deve partir da FAIXA EM REPRODUÇÃO (e do q' atualizado), não da última da fila.
    active_seed_id = current_track_id
    try:
        if status.get("state") == "play":
            curr_song = client.currentsong()
            curr_file = curr_song.get("file")
            if curr_file:
                norm_curr = normalize_mpd_filepath(curr_file, music_root)
                resolved_id = file_to_id_map.get(norm_curr) or file_to_id_map.get(curr_file)
                if resolved_id:
                    active_seed_id = resolved_id
    except Exception as e:
        logging.debug(f"Falha ao checar faixa em reprodução: {e}")

    while ahead < min_queue_ahead and attempts < max_tries:
        attempts += 1

        # Mapeia todas as músicas atualmente na fila (tanto normalizadas quanto originais)
        queued_files = set()
        for item in playlist:
            f = item.get("file", "")
            if f:
                queued_files.add(f)
                queued_files.add(normalize_mpd_filepath(f, music_root))

        # Requisitos 4 e 5: Apenas a primeira recomendação (top-1) gera e grava a decisão no SQLite.
        # As demais faixas (exploração / continuidade) são vinculadas à mesma decisão sem duplicar.
        is_first_rec = (added_count == 0)
        record_audit = is_first_rec

        selection = select_next_recommendations(
            collection=collection,
            current_track_id=active_seed_id,  # <-- SEMPRE parte da faixa em reprodução!
            id_to_file_map=id_to_file_map,
            k=CANDIDATES_K,
            history=play_history,
            queued_files=queued_files,
            failed_tracks=failed_tracks,
            selection_mode=selection_mode,
            top_n=top_n,
            random_seed=random_seed,
            msg_queue=msg_queue,
            recommendation_mode=recommendation_mode,
            use_feedback=use_feedback,
            seed_songid=seed_songid,
            gatilho=gatilho,
            record_audit=record_audit
        )

        if not selection:
            logging.warning("Não há candidatas disponíveis para repor a fila. Escutando sem interromper.")
            if msg_queue:
                msg_queue.put({"type": "log", "text": "Aviso: Sem candidatas para repor a fila"})
            break

        candidate_file, candidate_rec, candidate_rank = selection
        candidate_id = candidate_rec['track_id']
        dist = candidate_rec.get('distance', 0.0)

        if is_first_rec:
            current_decision_id = candidate_rec.get('decision_id')
            decision_id = current_decision_id
            origem = "recomendada"
        else:
            decision_id = current_decision_id
            origem = "exploracao" if candidate_rank > 0 else "recomendada"

        try:
            # Requisito 3: Inserir com addid em posição explícita (logo após a faixa atual)
            # de modo que a selecionada (top-1) seja sempre a próxima, seguida das demais por score.
            insert_pos = (current_pos + 1 + added_count) if current_pos != -1 else None

            song_id = mpd_add_recommendation_unified(
                client=client,
                file_path=candidate_file,
                position=insert_pos,
                decision_id=decision_id,
                origem=origem,
                feedback_storage=feedback_storage
            )

            logging.info(
                f"Recomendada '{candidate_file}' (posição #{candidate_rank + 1} na lista de candidatas, "
                f"distância: {dist:.4f}, songid={song_id})"
            )
            if msg_queue:
                msg_queue.put({"type": "recommendation", "text": f"{os.path.basename(candidate_file)} (Adicionada!)"})
                msg_queue.put({"type": "log", "text": f"Injetada: {os.path.basename(candidate_file)} (pos #{candidate_rank + 1})"})

            play_history.append(candidate_id)
            save_session_history(play_history)

            added_count += 1
            if on_rec_success:
                on_rec_success()

            # Atualiza imediatamente a fila conhecida
            queued_files.add(candidate_file)
            queued_files.add(normalize_mpd_filepath(candidate_file, music_root))

            playlist = client.playlistinfo()
            ahead = len(playlist) - (current_pos + 1) if current_pos != -1 else len(playlist)

        except CommandError as e:
            logging.error(f"Candidata '{candidate_file}' rejeitada (motivo: add falhou - {e})")
            failed_tracks.add(candidate_id)
            if on_error:
                on_error(e)
            if msg_queue:
                msg_queue.put({"type": "recommendation", "text": f"{os.path.basename(candidate_file)} (Falhou)"})
                msg_queue.put({"type": "log", "text": f"Candidata rejeitada (add falhou): {os.path.basename(candidate_file)}"})

    if feedback_storage:
        sync_mpd_queue_state(client, file_to_id_map, collection, music_root, feedback_storage)

    return added_count

def monitor_and_recommend(
    client: MPDClient,
    collection,
    file_to_id_map: dict,
    id_to_file_map: dict,
    trigger_mode: str = "on_change",
    music_root: str = "",
    metadata_path: str = "",
    known_fingerprints: dict = None,
    msg_queue: queue.Queue = None,
    recommendation_mode: str = "similarity",
    use_feedback: bool = True
) -> None:
    """Loop principal que aguarda mudanças no MPD e enfileira recomendações com garantia de reposição."""
    if known_fingerprints is None:
        known_fingerprints = {}
    last_processed_file = None
    prev_song = None
    prev_status = None

    # Inicializa detector de feedback se ativo
    feedback_detector = None
    if use_feedback and HAS_FEEDBACK:
        try:
            feedback_storage = feedback.FeedbackStorage()
            feedback_detector = feedback.FeedbackDetector(feedback_storage)
            logging.info("Detector de feedback implícito (skips/completas) ATIVO.")
            if msg_queue:
                msg_queue.put({"type": "log", "text": "Módulo de Feedback por Skip ATIVO"})
        except Exception as e:
            logging.warning(f"Não foi possível inicializar detector de feedback: {e}")

    def resolve_track_metadata(filepath_str: str) -> Optional[Dict[str, Any]]:
        tid = file_to_id_map.get(filepath_str)
        if tid:
            try:
                res = collection.get(ids=[tid], include=["metadatas"])
                metas = res.get("metadatas", [])
                if metas and metas[0]:
                    d = dict(metas[0])
                    d["track_id"] = tid
                    return d
            except Exception:
                pass
        return None

    # Limitar HISTORY_SIZE a no máximo 50% das faixas indexadas
    total_indexed = max(1, len(file_to_id_map))
    effective_history_size = min(HISTORY_SIZE_DEFAULT, max(2, total_indexed // 2))
    logging.info(f"Tamanho do histórico de sessão configurado: {effective_history_size} faixas (total indexado: {total_indexed}). Modo de recomendação: {recommendation_mode}. Feedback implícito: {'LIGADO' if (use_feedback and HAS_FEEDBACK) else 'DESLIGADO'}.")

    play_history = load_session_history(SESSION_HISTORY_FILE, max_len=effective_history_size)
    failed_tracks = set()
    last_decided_song_id: Optional[str] = None

    cnt_recs = 0
    cnt_idxs = 0
    cnt_errs = 0

    def update_counters():
        if msg_queue:
            msg_queue.put({"type": "counters", "recs": cnt_recs, "idxs": cnt_idxs, "errs": cnt_errs})

    def handle_rec_success():
        nonlocal cnt_recs
        cnt_recs += 1
        update_counters()

    def handle_err(e):
        nonlocal cnt_errs
        cnt_errs += 1
        update_counters()

    if msg_queue:
        msg_queue.put({"type": "status", "state": "monitorando"})
        update_counters()
    
    while True:
        try:
            client = reconnect_if_needed(client)
            
            # Requisito 1: Assinar/reagir apenas ao subsistema player (playlist e mixer são ignorados)
            events = client.idle("player")
            
            if "player" not in events:
                logging.debug(f"[Subsistema Ignorado] Eventos recebidos sem player: {events}")
                continue

            status = client.status()
            state = status.get("state")
            
            if state == "play":
                current_song = client.currentsong()
                current_song_id = str(current_song.get("id", ""))
                raw_file = current_song.get("file")
                if not raw_file:
                    continue
                    
                current_file = normalize_mpd_filepath(raw_file, music_root)

                # Requisito 3: Supressão de eventos autogerados na janela configurável (~1s)
                time_since_last_mut = time.time() - _last_queue_mutation_timestamp
                if time_since_last_mut < AUTOGENERATED_EVENT_SUPPRESSION_WINDOW:
                    logging.info(
                        f"[Supressão Autogerada] Evento recebido a {time_since_last_mut:.2f}s de alteração "
                        f"da fila (< {AUTOGENERATED_EVENT_SUPPRESSION_WINDOW}s). Descartando evento autogerado."
                    )
                    continue

                # Requisito 2: Idempotência por songid e arquivo
                if current_song_id and current_song_id == last_decided_song_id:
                    logging.debug(f"[Idempotência] Ignorando evento repetido para o mesmo seed songid={current_song_id}")
                    continue

                if current_file == last_processed_file and current_song_id == last_decided_song_id:
                    continue

                # Requisito 3: Lock em volta de "decidir + enfileirar"
                with RECOMMENDER_CYCLE_LOCK:
                    # Dupla checagem sob lock
                    if current_song_id and current_song_id == last_decided_song_id:
                        continue

                    # Avaliação de feedback implícito (skip / completa) da faixa anterior
                    if feedback_detector and prev_song and prev_status:
                        try:
                            ev = feedback_detector.evaluate_transition(
                                prev_song=prev_song,
                                prev_status=prev_status,
                                current_song=current_song,
                                current_status=status,
                                meta_resolver=resolve_track_metadata
                            )
                            if ev and msg_queue:
                                msg_queue.put({"type": "log", "text": f"Feedback registrado: {ev.upper()}"})
                        except Exception as e:
                            logging.warning(f"Erro ao detectar feedback: {e}")

                    prev_song = current_song
                    prev_status = status
                        
                    logging.info(f"Usuário ouvindo: {current_file} (songid={current_song_id})")
                    if msg_queue:
                        msg_queue.put({"type": "track", "name": os.path.basename(current_file)})
                        msg_queue.put({"type": "event", "name": "Faixa Trocada / Play"})
                        msg_queue.put({"type": "log", "text": f"Ouvindo: {os.path.basename(current_file)}"})
                    
                    last_processed_file = current_file
                    current_track_id = file_to_id_map.get(current_file)
                    
                    if not current_track_id:
                        logging.warning(f"Faixa atual '{current_file}' não encontrada no índice. Tentando indexação automática...")
                        if msg_queue:
                            msg_queue.put({"type": "status", "state": "indexando"})
                            msg_queue.put({"type": "log", "text": "Indexando nova faixa..."})
                        try:
                            abs_filepath = current_file if os.path.isabs(current_file) else os.path.join(music_root, current_file)
                            if not os.path.exists(abs_filepath):
                                logging.error(f"Arquivo não encontrado fisicamente: {abs_filepath}")
                                continue
                                
                            new_track_id = auto_indexer.index_unknown_track(
                                filepath=abs_filepath,
                                metadata_path=metadata_path,
                                collection=collection,
                                known_fingerprints=known_fingerprints,
                                music_library_root=music_root
                            )
                            
                            if new_track_id:
                                file_to_id_map[current_file] = new_track_id
                                id_to_file_map[new_track_id] = current_file
                                current_track_id = new_track_id
                                cnt_idxs += 1
                                update_counters()
                                if msg_queue:
                                    msg_queue.put({"type": "log", "text": "Faixa indexada com sucesso."})
                            else:
                                logging.warning("Falha na indexação automática. Nenhuma recomendação será gerada.")
                                if msg_queue:
                                    msg_queue.put({"type": "log", "text": "Falha na indexação."})
                                continue
                        finally:
                            if msg_queue:
                                msg_queue.put({"type": "status", "state": "monitorando"})
                    
                    # Registrar no histórico e salvar
                    if current_track_id not in play_history:
                        play_history.append(current_track_id)
                        save_session_history(play_history)

                    # Requisito 4 e 5: Repor a fila gerando exatamente uma decisão com top-1 na próxima posição
                    replenish_mpd_queue(
                        client=client,
                        collection=collection,
                        current_track_id=current_track_id,
                        file_to_id_map=file_to_id_map,
                        id_to_file_map=id_to_file_map,
                        music_root=music_root,
                        play_history=play_history,
                        failed_tracks=failed_tracks,
                        min_queue_ahead=MIN_QUEUE_AHEAD,
                        max_tries=MAX_REPLENISH_TRIES,
                        msg_queue=msg_queue,
                        on_rec_success=handle_rec_success,
                        on_error=handle_err,
                        recommendation_mode=recommendation_mode,
                        use_feedback=use_feedback,
                        seed_songid=current_song_id,
                        gatilho="player"
                    )

                    # Registrar idempotência para este songid
                    last_decided_song_id = current_song_id

                    # Sincroniza estado da fila no feedback.db para o monitor ao vivo
                    if feedback_detector:
                        sync_mpd_queue_state(client, file_to_id_map, collection, music_root, feedback_detector.storage)

            elif state == "stop":
                    # Fila esgotada ou usuário parou a reprodução
                    playlist = client.playlistinfo()
                    if len(playlist) == 0:
                        logging.warning("MPD em estado 'stop' com fila vazia. Repondo faixas na fila...")
                        if msg_queue:
                            msg_queue.put({"type": "log", "text": "MPD parado (fila vazia). Repondo fila..."})

                        # Usa a última faixa do histórico ou alguma faixa conhecida para repor
                        last_id = play_history[-1] if play_history else list(id_to_file_map.keys())[0] if id_to_file_map else None
                        if last_id:
                            replenish_mpd_queue(
                                client=client,
                                collection=collection,
                                current_track_id=last_id,
                                file_to_id_map=file_to_id_map,
                                id_to_file_map=id_to_file_map,
                                music_root=music_root,
                                play_history=play_history,
                                failed_tracks=failed_tracks,
                                min_queue_ahead=MIN_QUEUE_AHEAD,
                                max_tries=MAX_REPLENISH_TRIES,
                                msg_queue=msg_queue,
                                on_rec_success=handle_rec_success,
                                on_error=handle_err,
                                recommendation_mode=recommendation_mode,
                                use_feedback=use_feedback
                            )
                            # Se a constante permitir, retoma a reprodução automaticamente
                            if AUTO_RESUME_PLAY_ON_STOP:
                                try:
                                    client.play(0)
                                    logging.info("Reprodução retomada automaticamente após reposição da fila.")
                                except Exception as e:
                                    logging.error(f"Erro ao retomar reprodução: {e}")
                        
        except KeyboardInterrupt:
            raise
        except Exception as e:
            logging.error(f"Erro no ciclo de monitoramento: {e}")
            cnt_errs += 1
            update_counters()
            if msg_queue:
                msg_queue.put({"type": "status", "state": "erro"})
                msg_queue.put({"type": "log", "text": f"Erro: {e}"})
                msg_queue.put({"type": "status", "state": "monitorando"})

def run_recommender(
    metadata_path: str = None,
    music_root: str = None,
    mode: str = "cluster",
    trigger_mode: str = "on_change",
    gui: bool = True,
    use_feedback: bool = True,
    zerar_feedback: bool = False
) -> None:
    """
    Ponto de entrada público para executar o recomendador em primeiro plano.
    Reaproveitado tanto pelo CLI do mpd_integration quanto pelo iniciar.py.
    """
    if metadata_path is None:
        metadata_path = config.METADATA_PATH
    if music_root is None:
        music_root = config.get_music_library_root(config.MPD_CONF_PATH)

    music_root = os.path.abspath(music_root)
    logging.info(f"Iniciando Recomendador Musical. Pasta base: {music_root}")

    # Limpar feedback anterior se solicitado
    if zerar_feedback and HAS_FEEDBACK:
        try:
            fb_storage = feedback.FeedbackStorage()
            fb_storage.clear_history()
            logging.info("Histórico de feedback.db totalmente zerado via --zerar-feedback.")
        except Exception as e:
            logging.warning(f"Erro ao zerar feedback: {e}")

    # 1. Carregar metadados e mapear caminhos
    logging.info("Construindo mapeamento de arquivos...")
    file_to_id, id_to_file = build_file_to_id_map(metadata_path, music_root)
    if not file_to_id:
        raise ValueError(f"Nenhum arquivo mapeado a partir de {metadata_path}!")

    logging.info(f"Total de {len(file_to_id)} faixas mapeadas.")

    # 2. Carregar fingerprints
    known_fingerprints = auto_indexer.load_known_fingerprints(metadata_path)

    # 3. Conectar ChromaDB
    chroma_client = vector_store.get_client(config.CHROMA_PERSIST_DIR)
    collection = vector_store.get_or_create_collection(chroma_client, config.COLLECTION_NAME)

    # 4. Conectar MPD
    mpd_client = connect_mpd(config.MPD_HOST, config.MPD_PORT)
    logging.info(f"Conectado ao MPD em {config.MPD_HOST}:{config.MPD_PORT}.")

    print("\n=============================================")
    fb_label = "LIGADO" if use_feedback else "DESLIGADO (--sem-feedback)"
    print(f"Sistema de Recomendação Ativo (Modo: {mode} | Feedback: {fb_label})")
    print("Pressione Ctrl+C para encerrar.")
    print("=============================================\n")

    msg_queue = queue.Queue()

    # 5. Loop principal em Background Thread
    mpd_thread = threading.Thread(
        target=monitor_and_recommend,
        args=(mpd_client, collection, file_to_id, id_to_file, trigger_mode, music_root, metadata_path, known_fingerprints, msg_queue, mode, use_feedback),
        daemon=True
    )
    mpd_thread.start()

    # 6. Modo de exibição: Janela GUI ou Terminal
    try:
        if gui:
            win = status_window.StatusWindow(msg_queue)
            win.start()
        else:
            # Modo Console: consome logs da fila e aguarda Ctrl+C
            while mpd_thread.is_alive():
                try:
                    msg = msg_queue.get(timeout=1.0)
                    if msg.get("type") in ["log", "recommendation", "event"]:
                        logging.info(f"[{msg.get('type').upper()}] {msg.get('text', msg.get('name', ''))}")
                except queue.Empty:
                    pass
    except KeyboardInterrupt:
        logging.info("\nEncerrando sistema de recomendação graciosamente...")
    finally:
        try:
            mpd_client.disconnect()
        except Exception:
            pass


