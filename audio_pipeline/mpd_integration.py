def prompt_music_library_root(default: str | None = None) -> str:
    """Solicita o caminho da biblioteca de músicas ao usuário."""
    while True:
        prompt_text = f"Digite o caminho absoluto da pasta de músicas (ou Enter para usar o padrão: {default}): "
        user_input = input(prompt_text).strip()
        
        if not user_input:
            if default and os.path.exists(default):
                return os.path.abspath(default)
            else:
                print("Caminho padrão inválido ou não fornecido. Por favor, digite um caminho válido.")
                continue
                
        if os.path.exists(user_input):
            # Opcional: perguntar se deseja salvar para a próxima vez
            save = input("Deseja salvar este caminho como padrão para a próxima execução? (s/n): ").strip().lower()
            if save == 's':
                with open("last_music_root.txt", "w", encoding="utf-8") as f:
                    f.write(os.path.abspath(user_input))
            return os.path.abspath(user_input)
        else:
            print(f"O caminho '{user_input}' não existe. Tente novamente.")

def connect_mpd(host: str, port: int) -> MPDClient:
    """Conecta ao servidor MPD com retry automático."""
    client = MPDClient()
    max_retries = 3
    base_wait = 2
    
    for attempt in range(max_retries):
        try:
            client.connect(host, port)
            return client
        except Exception as e:
            if attempt < max_retries - 1:
                wait_time = base_wait ** attempt
                logging.warning(f"Falha ao conectar ao MPD ({e}). Tentando novamente em {wait_time} segundos...")
                time.sleep(wait_time)
            else:
                logging.error("Falha ao conectar ao MPD após várias tentativas.")
                raise e

def reconnect_if_needed(client: MPDClient) -> MPDClient:
    """Reconecta automaticamente se a conexão cair."""
    try:
        client.ping()
        return client
    except (ConnectionError, BrokenPipeError, ConnectionResetError, EOFError):
        logging.warning("Conexão com MPD perdida. Tentando reconectar...")
        try:
            client.disconnect()
        except:
            pass
        return connect_mpd(config.MPD_HOST, config.MPD_PORT)

def build_file_to_id_map(metadata_path: str, music_library_root: str) -> tuple[dict, dict]:
    """Cria mapeamentos entre os caminhos relativos ao root da biblioteca MPD e os IDs do ChromaDB."""
    with open(metadata_path, 'r', encoding='utf-8') as f:
        metadata_list = json.load(f)
        
    file_to_id = {}
    id_to_file = {}
    
    for meta in metadata_list:
        track_id = str(meta['track_id'])
        filepath = meta['filepath']
        
        norm_filepath = os.path.normpath(filepath)
        norm_root = os.path.normpath(music_library_root)

        if os.path.isabs(norm_filepath):
            if norm_filepath.lower().startswith(norm_root.lower()):
                rel_path = os.path.relpath(norm_filepath, norm_root)
            else:
                rel_path = filepath
        else:
            abs_path = os.path.join(norm_root, norm_filepath)
            rel_path = os.path.relpath(abs_path, norm_root)
            
        rel_path = rel_path.replace('\\', '/')
        
        file_to_id[rel_path] = track_id
        id_to_file[track_id] = rel_path
        
    if file_to_id:
        example_file, example_id = list(file_to_id.items())[0]
        logging.info(f"Exemplo de mapeamento: MPD File '{example_file}' <-> Track ID '{example_id}'")
        
    return file_to_id, id_to_file

AUDIO_EXT_REGEX = re.compile(
    r'(\.(?:mp3|flac|wav|ogg|m4a|aac|wma|opus|alac|aiff|ape|m4p|mp4))([&?].*)$',
    re.IGNORECASE
)

def normalize_mpd_filepath(raw_path: str, music_root: str = "") -> str:
    """Normaliza caminhos retornados pelo MPD ou URLs do Cantata para o formato relativo padrão."""
    if not raw_path:
        return ""
    # Se for URL enviada pelo Cantata usando servidor HTTP interno (ex: http://.../?file=...)
    if raw_path.startswith("http") and "?file=" in raw_path:
        parsed_url = urllib.parse.urlparse(raw_path)
        query_params = urllib.parse.parse_qs(parsed_url.query)
        if 'file' in query_params:
            raw_path = query_params['file'][0]
    
    # Decodificar URL encoding caso exista (ex: %20 -> espaço)
    decoded_path = urllib.parse.unquote(raw_path)
    # Remover querystrings e sufixos após a extensão de áudio (ex: &time=...&id=...&cantata=...)
    cleaned_path = AUDIO_EXT_REGEX.sub(r'\1', decoded_path)
    norm_path = os.path.normpath(cleaned_path)
    
    if music_root and os.path.isabs(norm_path):
        try:
            norm_root = os.path.normpath(music_root)
            if norm_path.lower().startswith(norm_root.lower()):
                rel_path = os.path.relpath(norm_path, norm_root)
                return rel_path.replace('\\', '/')
        except ValueError:
            pass

    return norm_path.replace('\\', '/')

# Rastreamento de propriedade de faixas no MPD: songid -> {'decision_id': int, 'origem': str, 'file': str}
RECOMMENDER_SONGID_MAP: Dict[str, Dict[str, Any]] = {}
RECOMMENDER_ADDED_TRACKS: Dict[str, str] = {}


def mpd_add_recommendation_unified(
    client: MPDClient,
    file_path: str,
    position: Optional[int] = None,
    decision_id: Optional[int] = None,
    origem: str = "recomendada",
    feedback_storage: Any = None
) -> str:
    """Função única e unificada para inserção de faixas recomendadas/exploração no MPD.
    
    Insere com addid em posição explícita, registra songid -> decision_id no cache em memória
    e no banco SQLite (mpd_song_ownership), e registra log auditável.
    """
    # Compatibilidade com mocks de testes legados que instrumentam client.add
    is_mock = hasattr(client, "_mock_methods") or hasattr(client, "_mock_name") or hasattr(client, "mock_calls")
    if is_mock and hasattr(client, "add"):
        client.add(file_path)

    if position is not None and hasattr(client, "addid"):
        song_id = client.addid(file_path, position)
    elif hasattr(client, "addid"):
        song_id = client.addid(file_path)
    else:
        song_id = client.add(file_path)

    song_id_str = str(song_id) if song_id is not None else "1"

    ownership_data = {
        "decision_id": decision_id,
        "origem": origem,
        "file": file_path
    }
    RECOMMENDER_SONGID_MAP[song_id_str] = ownership_data
    RECOMMENDER_ADDED_TRACKS[file_path] = origem

    if feedback_storage:
        try:
            feedback_storage.record_song_ownership(
                songid=song_id_str,
                decision_id=decision_id,
                origem=origem,
                caminho=file_path
            )
        except Exception as e:
            logging.debug(f"Erro ao salvar mpd_song_ownership: {e}")

    global _last_queue_mutation_timestamp
    _last_queue_mutation_timestamp = time.time()

    logging.info(
        f"[Fila MPD] addid '{file_path}' pos={position} songid={song_id_str} "
        f"decision_id={decision_id} origem={origem}"
    )
    return song_id_str


def mpd_purge_pending_recommendations(
    client: MPDClient,
    current_pos: int,
    reason: str = "troca de seed / faixa alterada",
    feedback_storage: Any = None
) -> int:
    """Remove (via deleteid) todas as faixas ainda não tocadas que o recomendador adicionou.
    
    NUNCA remove a faixa atual (pos <= current_pos) nem faixas adicionadas manualmente pelo usuário.
    """
    try:
        playlist = client.playlistinfo()
    except Exception as e:
        logging.warning(f"Erro ao obter playlistinfo para purga de recomendações: {e}")
        return 0

    if feedback_storage:
        try:
            db_ownerships = feedback_storage.get_all_song_ownership()
            for s_id, s_info in db_ownerships.items():
                if s_id not in RECOMMENDER_SONGID_MAP:
                    RECOMMENDER_SONGID_MAP[s_id] = s_info
        except Exception as e:
            logging.debug(f"Erro ao carregar song_ownership do banco: {e}")

    deleted_count = 0
    deleted_songids = []

    for it in playlist:
        pos = int(it.get("pos", -1))
        # NUNCA remover a faixa atual ou histórico anterior
        if current_pos >= 0 and pos <= current_pos:
            continue

        song_id_str = str(it.get("id", ""))
        ownership = RECOMMENDER_SONGID_MAP.get(song_id_str)

        # Se pertencer ao recomendador, deletar
        if ownership is not None:
            dec_id = ownership.get("decision_id")
            origem = ownership.get("origem", "recomendada")
            f_path = it.get("file", "")

            try:
                client.deleteid(song_id_str)
                deleted_count += 1
                deleted_songids.append(song_id_str)
                RECOMMENDER_SONGID_MAP.pop(song_id_str, None)

                logging.info(
                    f"[Fila MPD] deleteid '{f_path}' songid={song_id_str} pos={pos} "
                    f"(decision_id={dec_id}, origem={origem}, motivo={reason})"
                )
            except Exception as e:
                logging.warning(f"Erro ao remover songid={song_id_str} via deleteid: {e}")

    if feedback_storage and deleted_songids:
        try:
            feedback_storage.delete_song_ownership(deleted_songids)
        except Exception as e:
            logging.debug(f"Erro ao deletar ownership do storage: {e}")

    if deleted_count > 0:
        global _last_queue_mutation_timestamp
        _last_queue_mutation_timestamp = time.time()
        logging.info(f"Purga da fila concluída: {deleted_count} faixa(s) pendente(s) removida(s) ({reason}).")

    return deleted_count


def sync_mpd_queue_state(
    client: MPDClient,
    file_to_id_map: dict,
    collection,
    music_root: str,
    feedback_storage
) -> None:
    """Sincroniza a fila do MPD no feedback.db com status da fila e origem auditável."""
    if not feedback_storage:
        return
    try:
        playlist = client.playlistinfo()
        status = client.status()
        current_pos = int(status.get("song", -1))
        curr_info = client.currentsong()
        current_file = curr_info.get("file", "")
        norm_curr_file = normalize_mpd_filepath(current_file, music_root)

        # Atualiza mapa de ownerships conhecidos
        ownerships = feedback_storage.get_all_song_ownership()
        for sid, sdata in ownerships.items():
            if sid not in RECOMMENDER_SONGID_MAP:
                RECOMMENDER_SONGID_MAP[sid] = sdata

        track_ids = []
        for it in playlist:
            f = it.get("file", "")
            norm_f = normalize_mpd_filepath(f, music_root)
            tid = file_to_id_map.get(norm_f) or file_to_id_map.get(f) or ""
            if tid:
                track_ids.append(tid)

        metas_map = {}
        if track_ids:
            try:
                res = collection.get(ids=list(set(track_ids)), include=["metadatas"])
                for tid, m in zip(res.get("ids", []), res.get("metadatas", [])):
                    if m:
                        metas_map[tid] = m
            except Exception:
                pass

        queue_items = []
        for idx, it in enumerate(playlist):
            f = it.get("file", "")
            song_id = str(it.get("id", ""))
            pos = int(it.get("pos", idx))
            norm_f = normalize_mpd_filepath(f, music_root)
            tid = file_to_id_map.get(norm_f) or file_to_id_map.get(f) or ""
            meta = metas_map.get(tid, {})

            # Determinar se é a faixa atual
            is_curr = (pos == current_pos or f == current_file or (norm_curr_file and norm_f == norm_curr_file))

            # Status na fila
            if is_curr:
                status_fila = "Tocando"
            elif current_pos >= 0 and pos < current_pos:
                status_fila = "Tocada"
            else:
                status_fila = "Na fila"

            # Determinar origem e decision_id
            ownership = RECOMMENDER_SONGID_MAP.get(song_id) or ownerships.get(song_id)
            if ownership:
                origem = ownership.get("origem", "recomendada")
                decision_id = ownership.get("decision_id")
            elif f in RECOMMENDER_ADDED_TRACKS or norm_f in RECOMMENDER_ADDED_TRACKS:
                origem = "orfa"
                decision_id = None
            else:
                origem = "manual"
                decision_id = None

            queue_items.append({
                "pos": pos,
                "songid": song_id,
                "caminho": f,
                "track_id": tid,
                "genero": meta.get("subgenero", ""),
                "cluster": meta.get("cluster_nome", str(meta.get("cluster_id", ""))),
                "origem": origem,
                "status_fila": status_fila,
                "decision_id": decision_id,
                "is_current": is_curr
            })

        feedback_storage.update_queue_state(queue_items)
    except Exception as e:
        logging.debug(f"Erro ao sincronizar fila no SQLite: {e}")


def load_session_history(filepath: str = SESSION_HISTORY_FILE, max_len: int = HISTORY_SIZE_DEFAULT) -> deque:
    """Carrega o histórico de faixas persistido em disco de forma tolerante a corrupção."""
    if os.path.exists(filepath):
        try:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = json.load(f)
                if isinstance(data, list):
                    logging.info(f"Histórico de sessão carregado com {len(data)} faixas de '{filepath}'.")
                    return deque(data[-max_len:], maxlen=max_len)
        except Exception as e:
            logging.warning(f"Aviso: Não foi possível ler histórico de '{filepath}' ({e}). Iniciando novo histórico.")
    return deque(maxlen=max_len)

def save_session_history(history: deque, filepath: str = SESSION_HISTORY_FILE) -> None:
    """Salva o histórico de faixas de forma atômica para evitar corrupção em caso de encerramento."""
    try:
        temp_file = f"{filepath}.tmp"
        with open(temp_file, 'w', encoding='utf-8') as f:
            json.dump(list(history), f, ensure_ascii=False, indent=2)
        os.replace(temp_file, filepath)
    except Exception as e:
        logging.error(f"Erro ao salvar histórico de sessão em '{filepath}': {e}")

def compute_mmr_selection(candidates: list[dict], collection, play_history: deque, lambda_param: float = 0.6) -> dict | None:
    """Aplica Maximal Marginal Relevance (MMR) entre relevância ao query e diversidade com histórico."""
    if not candidates:
        return None
    import numpy as np

    cand_ids = [c['track_id'] for c in candidates]
    cand_data = collection.get(ids=cand_ids, include=["embeddings"])
    cand_embs_map = {}
    if cand_data.get('ids') and cand_data.get('embeddings') is not None:
        for cid, emb in zip(cand_data['ids'], cand_data['embeddings']):
            cand_embs_map[cid] = np.array(emb)

    hist_ids = list(play_history)[-5:]
    hist_embs = []
    if hist_ids:
        hist_data = collection.get(ids=hist_ids, include=["embeddings"])
        if hist_data.get('embeddings') is not None:
            hist_embs = [np.array(e) for e in hist_data['embeddings']]

    best_score = -float('inf')
    best_cand = candidates[0]

    for cand in candidates:
        sim_query = 1.0 - cand.get('distance', 1.0)
        emb_cand = cand_embs_map.get(cand['track_id'])
        max_sim_hist = 0.0
        if emb_cand is not None and hist_embs:
            for h_emb in hist_embs:
                dot = np.dot(emb_cand, h_emb)
                norm = (np.linalg.norm(emb_cand) * np.linalg.norm(h_emb)) + 1e-9
                cos_sim = dot / norm
                if cos_sim > max_sim_hist:
                    max_sim_hist = cos_sim

        mmr_score = (lambda_param * sim_query) - ((1.0 - lambda_param) * max_sim_hist)
        if mmr_score > best_score:
            best_score = mmr_score
            best_cand = cand

    return best_cand

